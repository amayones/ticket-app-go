CREATE TABLE IF NOT EXISTS CPROLEPERMISSION (
  ROLE_CODE TEXT NOT NULL REFERENCES CPROLE (CODE) ON DELETE CASCADE,
  PERMISSION_CODE TEXT NOT NULL REFERENCES CPPERMISSION (CODE) ON DELETE CASCADE,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ROLE_CODE, PERMISSION_CODE)
);
INSERT INTO CPROLEPERMISSION (ROLE_CODE, PERMISSION_CODE)
SELECT 'ADMIN', CODE FROM CPPERMISSION
WHERE NOT EXISTS (
  SELECT 1 FROM CPROLEPERMISSION x WHERE x.ROLE_CODE = 'ADMIN' AND x.PERMISSION_CODE = CPPERMISSION.CODE
);
INSERT INTO CPROLEPERMISSION (ROLE_CODE, PERMISSION_CODE)
SELECT 'USER', 'MENU_DASHBOARD'
WHERE NOT EXISTS (
  SELECT 1 FROM CPROLEPERMISSION
  WHERE ROLE_CODE = 'USER' AND PERMISSION_CODE = 'MENU_DASHBOARD'
);

CREATE TABLE IF NOT EXISTS CPAUDITLOG (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CODE TEXT NOT NULL UNIQUE,
  ACTOR_CODE TEXT,
  ACTION TEXT NOT NULL,
  ENTITY TEXT NOT NULL,
  ENTITY_CODE TEXT,
  DETAIL TEXT,
  IP_ADDRESS TEXT,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CPAUDIT_ACTION ON CPAUDITLOG (ACTION, CREATED_AT DESC);
CREATE INDEX IF NOT EXISTS IX_CPAUDIT_ACTOR ON CPAUDITLOG (ACTOR_CODE, CREATED_AT DESC);

CREATE TABLE IF NOT EXISTS CPSYSLOG (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  CODE TEXT NOT NULL UNIQUE,
  LEVEL TEXT NOT NULL,
  SOURCE TEXT NOT NULL,
  MESSAGE TEXT NOT NULL,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_CPSYS_LEVEL ON CPSYSLOG (LEVEL, CREATED_AT DESC);

