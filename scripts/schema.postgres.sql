CREATE TABLE IF NOT EXISTS T_CITY (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  NAME VARCHAR(100) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_EVENT (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  ORGANIZER_CODE VARCHAR(20) NOT NULL REFERENCES CPUSER (CODE),
  CITY_CODE VARCHAR(20) REFERENCES T_CITY (CODE),
  TITLE VARCHAR(200) NOT NULL,
  DESCRIPTION VARCHAR(1000),
  VENUE VARCHAR(200),
  START_AT TIMESTAMP NOT NULL,
  END_AT TIMESTAMP,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'PUBLISHED' CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'COMPLETED', 'CANCELLED')),
  PLATFORM_FEE_PERCENT DECIMAL(5,2) NOT NULL DEFAULT 10.00,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_TICKET_TYPE (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  EVENT_CODE VARCHAR(20) NOT NULL REFERENCES T_EVENT (CODE) ON DELETE CASCADE,
  NAME VARCHAR(100) NOT NULL,
  PRICE DECIMAL(18,2) NOT NULL DEFAULT 0,
  QUOTA INT NOT NULL DEFAULT 0,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_PROMO (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  EVENT_CODE VARCHAR(20) REFERENCES T_EVENT (CODE) ON DELETE CASCADE,
  PROMO_CODE VARCHAR(40) NOT NULL UNIQUE,
  DISCOUNT_PERCENT DECIMAL(5,2) NOT NULL DEFAULT 0,
  DISCOUNT_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0,
  MAX_USES INT,
  USED_COUNT INT NOT NULL DEFAULT 0,
  VALID_FROM TIMESTAMP NOT NULL,
  VALID_TO TIMESTAMP NOT NULL,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'EXPIRED', 'DISABLED')),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_ORDER (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  EVENT_CODE VARCHAR(20) NOT NULL REFERENCES T_EVENT (CODE),
  BUYER_CODE VARCHAR(20) NOT NULL REFERENCES CPUSER (CODE),
  TICKET_TYPE_CODE VARCHAR(20) NOT NULL REFERENCES T_TICKET_TYPE (CODE),
  QTY INT NOT NULL,
  GROSS_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0,
  DISCOUNT_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0,
  PLATFORM_FEE DECIMAL(18,2) NOT NULL DEFAULT 0,
  NET_AMOUNT DECIMAL(18,2) NOT NULL DEFAULT 0,
  PROMO_CODE VARCHAR(40),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'PAID' CHECK (STATUS IN ('PENDING', 'PAID', 'CANCELLED', 'REFUNDED')),
  ORDER_DATE TIMESTAMP NOT NULL DEFAULT NOW(),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_TICKET (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  ORDER_CODE VARCHAR(20) NOT NULL REFERENCES T_ORDER (CODE) ON DELETE CASCADE,
  QR_CODE VARCHAR(64) NOT NULL UNIQUE,
  HOLDER_NAME VARCHAR(100),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'USED', 'REFUNDED')),
  CHECKED_IN_AT TIMESTAMP,
  CHECKED_IN_BY VARCHAR(20) REFERENCES CPUSER (CODE),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_REFUND (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  ORDER_CODE VARCHAR(20) NOT NULL REFERENCES T_ORDER (CODE),
  AMOUNT DECIMAL(18,2) NOT NULL,
  REASON VARCHAR(500),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
  REQUESTED_BY VARCHAR(20) NOT NULL REFERENCES CPUSER (CODE),
  DECIDED_BY VARCHAR(20) REFERENCES CPUSER (CODE),
  DECIDED_AT TIMESTAMP,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

