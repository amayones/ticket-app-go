-- Discovery tables (prefix T_, mirror of scripts/migrate6_discovery.sql).
CREATE TABLE IF NOT EXISTS T_EVENT_CATEGORY (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  NAME VARCHAR(100) NOT NULL,
  SORT_ORDER INT NOT NULL DEFAULT 99,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_NEWS_CATEGORY (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  NAME VARCHAR(100) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_NEWS (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  TITLE VARCHAR(200) NOT NULL,
  SLUG VARCHAR(200) NOT NULL UNIQUE,
  SUMMARY VARCHAR(500),
  BODY TEXT NOT NULL,
  IMAGE_URL VARCHAR(500),
  NEWS_CATEGORY_CODE VARCHAR(20) NOT NULL REFERENCES T_NEWS_CATEGORY (CODE),
  EVENT_CATEGORY_CODE VARCHAR(20) REFERENCES T_EVENT_CATEGORY (CODE),
  EVENT_CODE VARCHAR(20) REFERENCES T_EVENT (CODE),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (STATUS IN ('DRAFT', 'PUBLISHED')),
  PUBLISHED_AT TIMESTAMP,
  VIEW_COUNT INT NOT NULL DEFAULT 0,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_NEWS_VIEW (
  ID SERIAL PRIMARY KEY,
  NEWS_CODE VARCHAR(20) NOT NULL REFERENCES T_NEWS (CODE) ON DELETE CASCADE,
  VIEWER_HASH VARCHAR(64) NOT NULL,
  VIEWED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_AD_CAMPAIGN (
  ID SERIAL PRIMARY KEY,
  CODE VARCHAR(20) NOT NULL UNIQUE,
  TITLE VARCHAR(200) NOT NULL,
  IMAGE_URL VARCHAR(500),
  TARGET_URL VARCHAR(500),
  POSITION VARCHAR(20) NOT NULL DEFAULT 'HOME_BANNER' CHECK (POSITION IN ('HOME_BANNER', 'EVENT_LIST', 'SIDEBAR')),
  START_AT TIMESTAMP NOT NULL,
  END_AT TIMESTAMP NOT NULL,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'PAUSED', 'ENDED')),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
  UPDATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS T_AD_EVENT (
  ID SERIAL PRIMARY KEY,
  CAMPAIGN_CODE VARCHAR(20) NOT NULL REFERENCES T_AD_CAMPAIGN (CODE) ON DELETE CASCADE,
  KIND VARCHAR(10) NOT NULL CHECK (KIND IN ('IMPRESSION', 'CLICK')),
  IP_HASH VARCHAR(64) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

